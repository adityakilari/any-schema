// Embeds /export-queries and /samples into src/generated/assets.js so the browser app
// (and the single-file build) can show them without fetching. Also refreshes the
// export-query sections of README.md between <!-- query:NAME --> markers.
// Run: npm run generate   (CI fails if the committed output is stale)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (dir) => Object.fromEntries(fs.readdirSync(path.join(root, dir)).sort().map((f) => [f, fs.readFileSync(path.join(root, dir, f), 'utf8')]));
const queries = read('export-queries');
const samples = read('samples');

const banner = '// AUTO-GENERATED by scripts/generate.mjs - do not edit. Run `npm run generate`.\n';
const out = `${banner}export const QUERIES = ${JSON.stringify(queries, null, 0)};\nexport const SAMPLES = ${JSON.stringify(samples, null, 0)};\n`;
const target = path.join(root, 'src/generated/assets.js');
const check = process.argv.includes('--check');
let stale = false;
if (check) stale = !fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== out;
else fs.writeFileSync(target, out);

// README query blocks
const readmePath = path.join(root, 'README.md');
if (fs.existsSync(readmePath)) {
  const readme = fs.readFileSync(readmePath, 'utf8');
  const lang = (f) => (f.endsWith('.sql') ? 'sql' : f.endsWith('.js') ? 'js' : f.endsWith('.sh') ? 'bash' : f.endsWith('.ps1') ? 'powershell' : f.endsWith('.soql') ? 'sql' : '');
  const next = readme.replace(/<!-- query:([\w.-]+) -->[\s\S]*?<!-- \/query -->/g, (m, f) => {
    if (!queries[f]) throw new Error(`README references unknown query file ${f}`);
    return `<!-- query:${f} -->\n\`\`\`${lang(f)}\n${queries[f].trimEnd()}\n\`\`\`\n<!-- /query -->`;
  });
  if (check) stale = stale || next !== readme;
  else fs.writeFileSync(readmePath, next);
}
if (check && stale) { console.error('Generated files are stale. Run `npm run generate` and commit.'); process.exit(1); }
console.log(check ? 'generated files up to date' : `wrote ${path.relative(root, target)} (${Object.keys(queries).length} queries, ${Object.keys(samples).length} samples)`);
